class Solution(object):
    def countCommas(self, n):
        if n < 1000:
            return 0

        elif n < 1000000:
            return n - 999

        elif n < 1000000000:
            return ((999999 - 999) * 1 +
                    (n - 999999) * 2)

        elif n < 1000000000000:
            return ((999999 - 999) * 1 +
                    (999999999 - 999999) * 2 +
                    (n - 999999999) * 3)

        elif n < 1000000000000000:
            return ((999999 - 999) * 1 +
                    (999999999 - 999999) * 2 +
                    (999999999999 - 999999999) * 3 +
                    (n - 999999999999) * 4)

        else:
            return ((999999 - 999) * 1 +
                    (999999999 - 999999) * 2 +
                    (999999999999 - 999999999) * 3 +
                    (999999999999999 - 999999999999) * 4 +
                    (n - 999999999999999) * 5)